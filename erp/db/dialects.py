"""SQL dialects for the supported database management systems.

Every piece of SQL that differs between database systems lives here, so the
rest of the application can stay database independent.  Supported systems:

* SQLite (built into Python, ideal for small installations and testing)
* MySQL and MariaDB (PyMySQL driver)
* Microsoft SQL Server (pyodbc or pymssql driver)
* PostgreSQL (psycopg 3 or psycopg2 driver)
"""

from __future__ import annotations

import datetime as dt
import decimal
import importlib
import re
from dataclasses import dataclass, field

# Allowed SQL identifiers: ASCII letters, digits and underscores, at most 63 characters (the PostgreSQL
# limit).
IDENT_RE = re.compile(r"^[A-Za-z_][A-Za-z0-9_]{0,62}$")


@dataclass(slots=True)
class Column:
    """A database independent column description."""

    name: str
    kind: str  # pk, int, varchar, text, decimal, float, bool, date, datetime
    nullable: bool = True
    length: int | None = None
    precision: int | None = None
    scale: int | None = None


@dataclass(slots=True)
class Table:
    """A database independent table description: columns plus ``(name, columns, unique)`` indexes."""
    name: str
    columns: list[Column]
    indexes: list[tuple[str, list[str], bool]] = field(default_factory=list)  # (name, cols, unique)

    def column(self, name: str) -> Column | None:
        """The column called ``name``, or ``None``."""
        for col in self.columns:
            if col.name == name:
                return col
        return None


class DialectError(Exception):
    """Raised for unsupported database systems, missing drivers and invalid identifiers."""
    pass


class Dialect:
    """Base class: standard SQL; subclasses override what their system does differently.

    One instance per system lives in :data:`DIALECTS`.  Dialects are stateless,
    so the same instance also renders SQL dumps for other systems (exports).
    """
    name = "generic"
    title = "Generic SQL"
    quote_open = '"'
    quote_close = '"'
    default_port: int | None = None
    #: how to obtain the generated primary key: "lastrowid", "returning" or "output"
    id_strategy = "lastrowid"
    drivers: tuple[str, ...] = ()
    needs_server = True

    # ------------------------------------------------------------------ names
    def quote(self, ident: str) -> str:
        """Quote an identifier.

        Identifiers are never taken from users unchecked: only names matching
        :data:`IDENT_RE` are accepted, so quoting can not be used for SQL injection.
        """
        if not IDENT_RE.match(ident):
            raise DialectError(f"Invalid SQL identifier: {ident!r}")
        return f"{self.quote_open}{ident}{self.quote_close}"

    # ------------------------------------------------------------------ connect
    def load_driver(self, preferred: str | None = None):
        """Import the preferred or the first available DB-API driver module."""
        names = [preferred] if preferred else list(self.drivers)
        errors = []
        for name in names:
            try:
                return importlib.import_module(name)
            except ImportError as exc:  # pragma: no cover - depends on environment
                errors.append(f"{name}: {exc}")
        raise DialectError(
            f"No database driver available for {self.title}. Install one of: "
            + ", ".join(self.drivers)
            + (" (" + "; ".join(errors) + ")" if errors else "")
        )

    def connect(self, cfg: dict):  # pragma: no cover - overridden
        """Open a DB-API connection with the parameters of the configuration file."""
        raise NotImplementedError

    def paramstyle(self, module) -> str:
        """Parameter style of ``module`` (``qmark``, ``format``, ``pyformat`` ...)."""
        return getattr(module, "paramstyle", "qmark")

    def init_connection(self, raw) -> None:
        """Hook executed on every new connection."""

    # ------------------------------------------------------------------ types
    def type_sql(self, col: Column) -> str:
        """SQL type for a column kind (see :class:`Column`)."""
        match col.kind:
            case "pk":
                return "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"
            case "int":
                return "BIGINT"
            case "varchar":
                return f"VARCHAR({col.length or 255})"
            case "text":
                return "TEXT"
            case "decimal":
                return f"DECIMAL({col.precision or 18},{col.scale if col.scale is not None else 2})"
            case "float":
                return "DOUBLE PRECISION"
            case "bool":
                return "BOOLEAN"
            case "date":
                return "DATE"
            case "datetime":
                return "TIMESTAMP"
        raise DialectError(f"Unknown column kind {col.kind!r}")

    def column_sql(self, col: Column) -> str:
        """Column definition used in CREATE TABLE and ALTER TABLE ADD."""
        sql = f"{self.quote(col.name)} {self.type_sql(col)}"
        if col.kind != "pk" and not col.nullable:
            sql += " NOT NULL"
        return sql

    # ------------------------------------------------------------------ DDL
    def create_table_sql(self, table: Table, if_not_exists: bool = True) -> list[str]:
        """CREATE TABLE plus one CREATE INDEX statement per index."""
        cols = ",\n  ".join(self.column_sql(c) for c in table.columns)
        ine = "IF NOT EXISTS " if if_not_exists else ""
        stmts = [f"CREATE TABLE {ine}{self.quote(table.name)} (\n  {cols}\n)"]
        for name, cols_, unique in table.indexes:
            stmts.append(self.create_index_sql(name, table.name, cols_, unique, if_not_exists))
        return stmts

    def create_index_sql(self, name, table, cols, unique=False, if_not_exists=True) -> str:
        """CREATE [UNIQUE] INDEX statement."""
        u = "UNIQUE " if unique else ""
        ine = "IF NOT EXISTS " if if_not_exists else ""
        collist = ", ".join(self.quote(c) for c in cols)
        return f"CREATE {u}INDEX {ine}{self.quote(name)} ON {self.quote(table)} ({collist})"

    def add_column_sql(self, table: str, col: Column) -> str:
        """ALTER TABLE ... ADD COLUMN (used when a field is added to an entity)."""
        return f"ALTER TABLE {self.quote(table)} ADD COLUMN {self.column_sql(col)}"

    def drop_column_sql(self, table: str, column: str) -> str:
        """ALTER TABLE ... DROP COLUMN (used when a field is deleted)."""
        return f"ALTER TABLE {self.quote(table)} DROP COLUMN {self.quote(column)}"

    def drop_table_sql(self, table: str) -> str:
        """DROP TABLE that does not fail when the table is missing."""
        return f"DROP TABLE IF EXISTS {self.quote(table)}"

    def table_exists_sql(self) -> str:
        """Query returning a count > 0 when the table given as parameter exists."""
        return "SELECT COUNT(*) FROM information_schema.tables WHERE table_name = ?"

    # ------------------------------------------------------------------ DML
    def limit_sql(self, limit: int | None, offset: int = 0) -> str:
        """LIMIT/OFFSET clause; ``limit=None`` means all rows."""
        if limit is None:
            return f" OFFSET {int(offset)}" if offset else ""
        return f" LIMIT {int(limit)} OFFSET {int(offset)}"

    def insert_sql(self, table: str, cols: list[str], return_id: bool) -> str:
        """INSERT statement, extended so that the generated id can be read back."""
        t = self.quote(table)
        if cols:
            collist = ", ".join(self.quote(c) for c in cols)
            marks = ", ".join("?" for _ in cols)
            sql = f"INSERT INTO {t} ({collist}) VALUES ({marks})"
        else:
            sql = f"INSERT INTO {t} DEFAULT VALUES"
        if return_id and self.id_strategy == "returning":
            sql += f" RETURNING {self.quote('id')}"
        return sql

    def explicit_id_begin(self, table: str) -> list[str]:
        """Statements needed before inserting rows with explicit ids (restores)."""
        return []

    def explicit_id_end(self, table: str) -> list[str]:
        """Statements needed after inserting rows with explicit ids (e.g. reset sequences)."""
        return []

    def fold_sql(self, expr: str) -> str:
        """SQL version of :func:`fold_text`: lower case, Turkish dotless/dotted i as "i"."""
        # LOWER('I') is 'i' but Turkish needs 'ı'; LOWER('İ') may give 'i' plus a combining dot (U+0307).
        # Mapping 'ı' to 'i' and removing U+0307 makes 'ISTANBUL', 'İstanbul' and 'istanbul' all match.
        dotless, dot = self.string_literal("\u0131"), self.string_literal("\u0307")
        return f"REPLACE(REPLACE(LOWER({expr}), {dotless}, 'i'), {dot}, '')"

    def like_sql(self, expr: str) -> str:
        """Case and Turkish-i insensitive ``expr LIKE ?`` with ``!`` as escape character."""
        return f"{self.fold_sql(expr)} LIKE ? ESCAPE '!'"

    @staticmethod
    def escape_like(text: str) -> str:
        """Escape LIKE wildcards so ``%`` and ``_`` in a search text match literally."""
        return text.replace("!", "!!").replace("%", "!%").replace("_", "!_")

    def search_term(self, text: str) -> str:
        """Prepare a search text for :meth:`like_sql` (``%`` and ``_`` match literally)."""
        return "%" + self.escape_like(fold_text(text.strip())) + "%"

    def numeric_order_sql(self, expr: str) -> str:
        """ORDER BY expression for a decimal column (unchanged where decimals are numeric)."""
        return expr

    def cast_text_sql(self, expr: str) -> str:
        """Cast a number or date to text, so it can be searched with LIKE."""
        return f"CAST({expr} AS VARCHAR(255))"

    # ------------------------------------------------------------------ literals
    def string_literal(self, value: str) -> str:
        """SQL string literal (single quotes doubled)."""
        return "'" + value.replace("'", "''") + "'"

    def bool_literal(self, value: bool) -> str:
        """SQL literal for a boolean value."""
        return "TRUE" if value else "FALSE"

    def literal(self, value) -> str:
        """Render a Python value as an SQL literal for dump files."""
        if value is None:
            return "NULL"
        if isinstance(value, bool):
            return self.bool_literal(value)
        if isinstance(value, int):
            return str(value)
        if isinstance(value, float):
            # NaN and infinity have no portable SQL literal; NaN is the only value that is not equal to
            # itself.
            if value != value or value in (float("inf"), float("-inf")):
                return "NULL"
            return repr(value)
        if isinstance(value, decimal.Decimal):
            return format(value, "f")
        if isinstance(value, dt.datetime):
            return self.string_literal(value.replace(tzinfo=None).isoformat(sep=" "))
        if isinstance(value, dt.date):
            return self.string_literal(value.isoformat())
        if isinstance(value, (bytes, bytearray, memoryview)):
            return "X'" + bytes(value).hex() + "'"
        return self.string_literal(str(value))

    def comment(self, text: str) -> str:
        """Turn text into SQL line comments (header of dump files)."""
        return "\n".join("-- " + line for line in text.splitlines())

    def dump_preamble(self) -> list[str]:
        """Statements at the beginning of an SQL dump (transaction, settings)."""
        return []

    def dump_postamble(self) -> list[str]:
        """Statements at the end of an SQL dump."""
        return []

    def statement_terminator(self) -> str:
        """Separator written after each statement of an SQL dump."""
        return ";"


class SQLiteDialect(Dialect):
    """SQLite: a single file, no server; ideal for small installations and the tests."""
    name = "sqlite"
    title = "SQLite"
    drivers = ("sqlite3",)
    needs_server = False

    def connect(self, cfg: dict):
        """Open the database file.

        ``check_same_thread=False`` because connections move between the worker
        threads of the pool (one thread at a time).  WAL mode lets readers work
        while another connection writes; ``erp_fold`` is the Unicode aware lower
        case function used by searches (SQLite's LOWER only knows ASCII).
        """
        import sqlite3

        _register_sqlite_types(sqlite3)
        path = cfg.get("name") or cfg.get("path") or "erp.sqlite3"
        conn = sqlite3.connect(
            path, detect_types=sqlite3.PARSE_DECLTYPES, check_same_thread=False, timeout=30
        )
        conn.execute("PRAGMA foreign_keys = ON")
        conn.create_function("erp_fold", 1, fold_text, deterministic=True)
        if path != ":memory:":
            conn.execute("PRAGMA journal_mode = WAL")
        return conn

    def paramstyle(self, module) -> str:
        """sqlite3 always uses ``?`` placeholders."""
        return "qmark"

    def type_sql(self, col: Column) -> str:
        """SQLite types; AUTOINCREMENT keeps ids of deleted rows from being reused."""
        match col.kind:
            case "pk":
                return "INTEGER PRIMARY KEY AUTOINCREMENT"
            case "int":
                return "INTEGER"
            case "float":
                return "REAL"
            case "datetime":
                return "DATETIME"
            case "decimal":
                # A plain DECIMAL column has NUMERIC affinity: SQLite would turn
                # "123456789012345.6789" into a binary float and keep only about
                # 15 significant digits.  "TEXT" in the declared type gives TEXT
                # affinity, so amounts are stored exactly; the first word
                # "DECIMAL" still selects the Decimal converter when reading.
                return f"DECIMAL TEXT({col.precision or 18},{col.scale if col.scale is not None else 2})"
        return super().type_sql(col)

    def numeric_order_sql(self, expr: str) -> str:
        """Decimals are stored as text: sort by their numeric value, not alphabetically."""
        return f"CAST({expr} AS REAL)"

    def table_exists_sql(self) -> str:
        """Look the table up in ``sqlite_master``."""
        return "SELECT COUNT(*) FROM sqlite_master WHERE type = 'table' AND name = ?"

    def bool_literal(self, value: bool) -> str:
        """SQLite stores booleans as 1 and 0."""
        return "1" if value else "0"

    def limit_sql(self, limit, offset=0) -> str:
        """SQLite needs ``LIMIT -1`` to use OFFSET without a limit."""
        if limit is None:
            return f" LIMIT -1 OFFSET {int(offset)}" if offset else ""
        return super().limit_sql(limit, offset)

    def cast_text_sql(self, expr: str) -> str:
        """SQLite has no VARCHAR length; cast to TEXT."""
        return f"CAST({expr} AS TEXT)"

    def like_sql(self, expr: str) -> str:
        """Search with the Python based ``erp_fold`` function registered on every connection."""
        # SQLite's LOWER() only knows ASCII; use a Unicode aware function.
        return f"erp_fold({expr}) LIKE ? ESCAPE '!'"

    def search_term(self, text: str) -> str:
        """LIKE pattern for a search text (folded by :func:`fold_text`)."""
        return "%" + self.escape_like(fold_text(text.strip())) + "%"

    def dump_preamble(self) -> list[str]:
        """Disable foreign key checks and wrap the dump in one transaction."""
        return ["PRAGMA foreign_keys = OFF", "BEGIN TRANSACTION"]

    def dump_postamble(self) -> list[str]:
        """Commit the dump transaction."""
        return ["COMMIT"]


class MySQLDialect(Dialect):
    """MySQL (PyMySQL driver); identifiers are quoted with backticks."""
    name = "mysql"
    title = "MySQL"
    quote_open = "`"
    quote_close = "`"
    default_port = 3306
    drivers = ("pymysql",)

    def connect(self, cfg: dict):
        """Connect with utf8mb4, so every Unicode character (also emoji) can be stored."""
        mod = self.load_driver(cfg.get("driver") or None)
        return mod.connect(
            host=cfg.get("host") or "localhost",
            port=int(cfg.get("port") or self.default_port),
            user=cfg.get("user") or "",
            password=cfg.get("password") or "",
            database=cfg.get("name") or "",
            charset="utf8mb4",
            autocommit=False,
        )

    def init_connection(self, raw) -> None:
        """Use UTC for the session: all date-times are stored in UTC."""
        cur = raw.cursor()
        cur.execute("SET time_zone = '+00:00'")
        cur.close()

    def type_sql(self, col: Column) -> str:
        """MySQL types: LONGTEXT for long text, TINYINT(1) for booleans, microsecond DATETIME."""
        match col.kind:
            case "pk":
                return "BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY"
            case "text":
                return "LONGTEXT"
            case "float":
                return "DOUBLE"
            case "bool":
                return "TINYINT(1)"
            case "datetime":
                return "DATETIME(6)"
        return super().type_sql(col)

    def create_table_sql(self, table: Table, if_not_exists: bool = True) -> list[str]:
        """InnoDB table with utf8mb4 and the indexes inside CREATE TABLE."""
        # MySQL has no "CREATE INDEX IF NOT EXISTS", so indexes are part of CREATE TABLE.
        parts = [self.column_sql(c) for c in table.columns]
        for name, cols, unique in table.indexes:
            collist = ", ".join(self.quote(c) for c in cols)
            parts.append(f"{'UNIQUE ' if unique else ''}KEY {self.quote(name)} ({collist})")
        ine = "IF NOT EXISTS " if if_not_exists else ""
        body = ",\n  ".join(parts)
        return [f"CREATE TABLE {ine}{self.quote(table.name)} (\n  {body}\n) "
                "ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci"]

    def create_index_sql(self, name, table, cols, unique=False, if_not_exists=True) -> str:
        """Plain CREATE INDEX: MySQL does not know IF NOT EXISTS here."""
        return super().create_index_sql(name, table, cols, unique, False)

    def table_exists_sql(self) -> str:
        """Look the table up in the current database."""
        return (
            "SELECT COUNT(*) FROM information_schema.tables "
            "WHERE table_schema = DATABASE() AND table_name = ?"
        )

    def insert_sql(self, table, cols, return_id) -> str:
        """MySQL has no DEFAULT VALUES; ``() VALUES ()`` inserts a row of defaults."""
        if not cols:
            return f"INSERT INTO {self.quote(table)} () VALUES ()"
        return super().insert_sql(table, cols, return_id)

    def string_literal(self, value: str) -> str:
        """MySQL also treats backslashes in strings as escape characters."""
        value = value.replace("\\", "\\\\").replace("'", "''").replace("\x00", "\\0")
        return "'" + value + "'"

    def bool_literal(self, value: bool) -> str:
        """Booleans are TINYINT(1): 1 and 0."""
        return "1" if value else "0"

    def cast_text_sql(self, expr: str) -> str:
        """MySQL casts to CHAR, not VARCHAR."""
        return f"CAST({expr} AS CHAR)"

    def dump_preamble(self) -> list[str]:
        """Set the connection character set and disable foreign key checks."""
        return [
            "SET NAMES utf8mb4",
            "SET FOREIGN_KEY_CHECKS = 0",
            "START TRANSACTION",
        ]

    def dump_postamble(self) -> list[str]:
        """Commit and enable foreign key checks again."""
        return ["COMMIT", "SET FOREIGN_KEY_CHECKS = 1"]


class MariaDBDialect(MySQLDialect):
    """MariaDB: MySQL compatible; may also use the official ``mariadb`` connector."""
    name = "mariadb"
    title = "MariaDB"
    drivers = ("pymysql", "mariadb")

    def connect(self, cfg: dict):
        """Connect with the ``mariadb`` connector when configured, else like MySQL."""
        driver = cfg.get("driver") or "pymysql"
        if driver == "mariadb":  # pragma: no cover - optional connector
            mod = self.load_driver("mariadb")
            return mod.connect(
                host=cfg.get("host") or "localhost",
                port=int(cfg.get("port") or self.default_port),
                user=cfg.get("user") or "",
                password=cfg.get("password") or "",
                database=cfg.get("name") or "",
                autocommit=False,
            )
        return super().connect(cfg)


class MSSQLDialect(Dialect):
    """Microsoft SQL Server (pyodbc or pymssql); identifiers are quoted with brackets."""
    name = "mssql"
    title = "Microsoft SQL Server"
    quote_open = "["
    quote_close = "]"
    default_port = 1433
    id_strategy = "output"
    drivers = ("pyodbc", "pymssql")

    def connect(self, cfg: dict):
        """Connect with pyodbc (ODBC connection string) or pymssql.

        The password is wrapped in braces with ``}`` doubled, so it may contain
        ``;`` and other special characters.  Encryption is on by default; the
        server certificate is trusted unless ``trust_server_certificate`` is false.
        """
        driver = cfg.get("driver") or None
        mod = self.load_driver(driver)
        host = cfg.get("host") or "localhost"
        port = int(cfg.get("port") or self.default_port)
        if mod.__name__ == "pyodbc":
            odbc = cfg.get("odbc_driver") or "ODBC Driver 18 for SQL Server"
            parts = [
                f"DRIVER={{{odbc}}}",
                f"SERVER={host},{port}",
                f"DATABASE={cfg.get('name') or ''}",
                f"UID={cfg.get('user') or ''}",
                "PWD={" + (cfg.get("password") or "").replace("}", "}}") + "}",
                "TrustServerCertificate=" + ("yes" if cfg.get("trust_server_certificate", True) else "no"),
                "Encrypt=" + ("yes" if cfg.get("encrypt", True) else "no"),
            ]
            return mod.connect(";".join(parts), autocommit=False)
        return mod.connect(  # pragma: no cover - pymssql
            server=host,
            port=str(port),
            user=cfg.get("user") or "",
            password=cfg.get("password") or "",
            database=cfg.get("name") or "",
            autocommit=False,
        )

    def type_sql(self, col: Column) -> str:
        """SQL Server types: NVARCHAR for Unicode text, BIT for booleans, DATETIME2."""
        match col.kind:
            case "pk":
                return "BIGINT IDENTITY(1,1) NOT NULL PRIMARY KEY"
            case "varchar":
                n = col.length or 255
                return f"NVARCHAR({n})" if n <= 4000 else "NVARCHAR(MAX)"
            case "text":
                return "NVARCHAR(MAX)"
            case "float":
                return "FLOAT"
            case "bool":
                return "BIT"
            case "datetime":
                return "DATETIME2"
        return super().type_sql(col)

    def create_table_sql(self, table: Table, if_not_exists: bool = True) -> list[str]:
        """SQL Server has no CREATE TABLE IF NOT EXISTS; use OBJECT_ID()."""
        stmts = super().create_table_sql(table, False)
        if if_not_exists:
            lit = self.string_literal(table.name)
            stmts[0] = f"IF OBJECT_ID({lit}, 'U') IS NULL\n" + stmts[0]
        return stmts

    def create_index_sql(self, name, table, cols, unique=False, if_not_exists=True) -> str:
        """Guard the index with a lookup in ``sys.indexes``."""
        sql = super().create_index_sql(name, table, cols, unique, False)
        if if_not_exists:
            sql = (
                f"IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = {self.string_literal(name)})\n"
                + sql
            )
        return sql

    def add_column_sql(self, table: str, col: Column) -> str:
        """SQL Server writes ``ADD`` without ``COLUMN``."""
        return f"ALTER TABLE {self.quote(table)} ADD {self.column_sql(col)}"

    def drop_table_sql(self, table: str) -> str:
        """DROP TABLE guarded by OBJECT_ID() (works on old servers too)."""
        return f"IF OBJECT_ID({self.string_literal(table)}, 'U') IS NOT NULL DROP TABLE {self.quote(table)}"

    def table_exists_sql(self) -> str:
        """Look the table up in INFORMATION_SCHEMA."""
        return "SELECT COUNT(*) FROM INFORMATION_SCHEMA.TABLES WHERE TABLE_NAME = ?"

    def limit_sql(self, limit, offset=0) -> str:
        """OFFSET ... FETCH; the application always adds the required ORDER BY."""
        # Requires an ORDER BY clause, which the application always provides.
        sql = f" OFFSET {int(offset)} ROWS"
        if limit is not None:
            sql += f" FETCH NEXT {int(limit)} ROWS ONLY"
        return sql

    def insert_sql(self, table, cols, return_id) -> str:
        """INSERT with ``OUTPUT INSERTED.id`` to return the generated id."""
        t = self.quote(table)
        out = f" OUTPUT INSERTED.{self.quote('id')}" if return_id else ""
        if not cols:
            return f"INSERT INTO {t}{out} DEFAULT VALUES"
        collist = ", ".join(self.quote(c) for c in cols)
        marks = ", ".join("?" for _ in cols)
        return f"INSERT INTO {t} ({collist}){out} VALUES ({marks})"

    def explicit_id_begin(self, table: str) -> list[str]:
        """Allow explicit values for the IDENTITY column."""
        return [f"SET IDENTITY_INSERT {self.quote(table)} ON"]

    def explicit_id_end(self, table: str) -> list[str]:
        """Switch IDENTITY_INSERT off again."""
        return [f"SET IDENTITY_INSERT {self.quote(table)} OFF"]

    def cast_text_sql(self, expr: str) -> str:
        """Cast to NVARCHAR for searching."""
        return f"CAST({expr} AS NVARCHAR(4000))"

    @staticmethod
    def escape_like(text: str) -> str:
        """SQL Server also treats ``[`` as a LIKE wildcard."""
        return Dialect.escape_like(text).replace("[", "![")

    def string_literal(self, value: str) -> str:
        """Unicode string literal (``N'...'``)."""
        return "N'" + value.replace("'", "''") + "'"

    def bool_literal(self, value: bool) -> str:
        """Booleans are BIT: 1 and 0."""
        return "1" if value else "0"

    def literal(self, value) -> str:
        """SQL Server specific literals for date-times and binary data."""
        if isinstance(value, dt.datetime):
            return "'" + value.replace(tzinfo=None).isoformat(sep="T") + "'"
        if isinstance(value, (bytes, bytearray, memoryview)):
            return "0x" + bytes(value).hex()
        return super().literal(value)

    def dump_preamble(self) -> list[str]:
        """Abort the whole dump on the first error and use one transaction."""
        return ["SET XACT_ABORT ON", "BEGIN TRANSACTION"]

    def dump_postamble(self) -> list[str]:
        """Commit the dump transaction."""
        return ["COMMIT TRANSACTION"]


class PostgreSQLDialect(Dialect):
    """PostgreSQL (psycopg 3 or psycopg2)."""
    name = "postgresql"
    title = "PostgreSQL"
    default_port = 5432
    id_strategy = "returning"
    drivers = ("psycopg", "psycopg2")

    def connect(self, cfg: dict):
        """Connect to the configured database, always talking UTF-8.

        ``client_encoding`` matters for databases created with the SQL_ASCII
        encoding (the default of ``initdb`` under the C/POSIX locale): without
        it the drivers return text columns as ``bytes``, so for example no
        password hash would ever match and nobody could log in.
        """
        mod = self.load_driver(cfg.get("driver") or None)
        return mod.connect(
            host=cfg.get("host") or "localhost",
            port=int(cfg.get("port") or self.default_port),
            user=cfg.get("user") or "",
            password=cfg.get("password") or "",
            dbname=cfg.get("name") or "",
            client_encoding="UTF8",
        )

    def init_connection(self, raw) -> None:
        """Use UTC for the session: all date-times are stored in UTC."""
        cur = raw.cursor()
        cur.execute("SET TIME ZONE 'UTC'")
        cur.close()
        raw.commit()

    def table_exists_sql(self) -> str:
        """Look the table up in the current schema."""
        return (
            "SELECT COUNT(*) FROM information_schema.tables "
            "WHERE table_schema = current_schema() AND table_name = ?"
        )

    def explicit_id_end(self, table: str) -> list[str]:
        """Move the identity sequence past the highest restored id."""
        t = self.quote(table)
        name = self.string_literal(table)
        return [
            f"SELECT setval(pg_get_serial_sequence({name}, 'id'), "
            f"COALESCE((SELECT MAX({self.quote('id')}) FROM {t}), 0) + 1, false)"
        ]

    def cast_text_sql(self, expr: str) -> str:
        """PostgreSQL casts to TEXT."""
        return f"CAST({expr} AS TEXT)"

    def fold_sql(self, expr: str) -> str:
        """Locale independent version of :func:`fold_text`.

        PostgreSQL's LOWER() follows the database's LC_CTYPE: in databases
        created with the C or POSIX locale (common on servers and in
        containers) it only lowers ASCII, so "ÇAĞRI" would stay "ÇaĞri" and
        Turkish searches would miss.  TRANSLATE() maps the letters itself,
        including İ and ı to i, before LOWER() handles A-Z.
        """
        upper, lower = _FOLD_FROM, _FOLD_TO
        return f"LOWER(TRANSLATE({expr}, {self.string_literal(upper)}, {self.string_literal(lower)}))"

    def literal(self, value) -> str:
        """PostgreSQL specific literal for binary data (bytea)."""
        if isinstance(value, (bytes, bytearray, memoryview)):
            return "'\\x" + bytes(value).hex() + "'::bytea"
        return super().literal(value)

    def dump_preamble(self) -> list[str]:
        """Declare the dump as UTF-8 and use one transaction."""
        return ["SET client_encoding = 'UTF8'", "BEGIN"]

    def dump_postamble(self) -> list[str]:
        """Commit the dump transaction."""
        return ["COMMIT"]


def _fold_table() -> tuple[str, str]:
    """Upper case letters of the Latin, Greek and Cyrillic blocks and their lower case form.

    Built from Python's Unicode data, so the database side folds exactly like
    :func:`fold_text`.  ``İ`` and ``ı`` both become ``i``, as in :func:`fold_text`.
    """
    src, dst = ["İ", "ı"], ["i", "i"]
    for code in list(range(0x00C0, 0x0250)) + list(range(0x0370, 0x0530)):
        ch = chr(code)
        low = ch.lower()
        if ch in ("İ", "ı") or low == ch or len(low) != 1:
            continue
        src.append(ch)
        dst.append(low)
    return "".join(src), "".join(dst)


def fold_text(value):
    """Case folding for searches that treats Turkish dotted/dotless i alike."""
    if value is None:
        return None
    text = str(value)
    # Replace before lower(): 'İ'.lower() would produce 'i' + U+0307.
    for ch in ("İ", "I", "ı"):
        text = text.replace(ch, "i")
    return text.lower()


_FOLD_FROM, _FOLD_TO = _fold_table()

_SQLITE_REGISTERED = False


def _register_sqlite_types(sqlite3) -> None:
    """Teach the ``sqlite3`` module the types SQLite does not have (once per process).

    Adapters store dates, date-times and decimals as ISO text; converters turn
    the declared column types back into Python objects when reading.  Values
    that can not be converted are returned as text instead of failing.
    """
    global _SQLITE_REGISTERED
    if _SQLITE_REGISTERED:
        return
    sqlite3.register_adapter(dt.datetime, lambda v: v.replace(tzinfo=None).isoformat(sep=" "))
    sqlite3.register_adapter(dt.date, lambda v: v.isoformat())
    sqlite3.register_adapter(decimal.Decimal, lambda v: format(v, "f"))

    def conv_datetime(b: bytes):
        try:
            return dt.datetime.fromisoformat(b.decode())
        except ValueError:
            return b.decode()

    def conv_date(b: bytes):
        try:
            return dt.date.fromisoformat(b.decode()[:10])
        except ValueError:
            return b.decode()

    def conv_decimal(b: bytes):
        try:
            return decimal.Decimal(b.decode())
        except decimal.InvalidOperation:
            return b.decode()

    sqlite3.register_converter("DATETIME", conv_datetime)
    sqlite3.register_converter("TIMESTAMP", conv_datetime)
    sqlite3.register_converter("DATE", conv_date)
    sqlite3.register_converter("DECIMAL", conv_decimal)
    sqlite3.register_converter("BOOLEAN", lambda b: b not in (b"0", b"", b"false"))
    _SQLITE_REGISTERED = True


DIALECTS: dict[str, Dialect] = {
    d.name: d
    for d in (SQLiteDialect(), MySQLDialect(), MariaDBDialect(), MSSQLDialect(), PostgreSQLDialect())
}


def get_dialect(name: str) -> Dialect:
    """The dialect called ``name`` (sqlite, mysql, mariadb, mssql, postgresql)."""
    try:
        return DIALECTS[name]
    except KeyError:
        raise DialectError(f"Unsupported database system: {name!r}") from None
