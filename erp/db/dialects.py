"""SQL dialects for the supported database management systems.

Every piece of SQL that differs between database systems lives here, so the
rest of the application can stay database independent.  Supported systems:

* SQLite (built into Python, ideal for small installations and testing)
* MySQL and MariaDB (PyMySQL driver)
* Microsoft SQL Server (pyodbc or pymssql driver)
* PostgreSQL (psycopg 3 or psycopg2 driver)
"""

from __future__ import annotations

import datetime as dt
import decimal
import importlib
import re
from dataclasses import dataclass, field

IDENT_RE = re.compile(r"^[A-Za-z_][A-Za-z0-9_]{0,62}$")


@dataclass(slots=True)
class Column:
    """A database independent column description."""

    name: str
    kind: str  # pk, int, varchar, text, decimal, float, bool, date, datetime
    nullable: bool = True
    length: int | None = None
    precision: int | None = None
    scale: int | None = None


@dataclass(slots=True)
class Table:
    name: str
    columns: list[Column]
    indexes: list[tuple[str, list[str], bool]] = field(default_factory=list)  # (name, cols, unique)

    def column(self, name: str) -> Column | None:
        for col in self.columns:
            if col.name == name:
                return col
        return None


class DialectError(Exception):
    pass


class Dialect:
    name = "generic"
    title = "Generic SQL"
    quote_open = '"'
    quote_close = '"'
    default_port: int | None = None
    #: how to obtain the generated primary key: "lastrowid", "returning" or "output"
    id_strategy = "lastrowid"
    drivers: tuple[str, ...] = ()
    needs_server = True

    # ------------------------------------------------------------------ names
    def quote(self, ident: str) -> str:
        if not IDENT_RE.match(ident):
            raise DialectError(f"Invalid SQL identifier: {ident!r}")
        return f"{self.quote_open}{ident}{self.quote_close}"

    # ------------------------------------------------------------------ connect
    def load_driver(self, preferred: str | None = None):
        names = [preferred] if preferred else list(self.drivers)
        errors = []
        for name in names:
            try:
                return importlib.import_module(name)
            except ImportError as exc:  # pragma: no cover - depends on environment
                errors.append(f"{name}: {exc}")
        raise DialectError(
            f"No database driver available for {self.title}. Install one of: "
            + ", ".join(self.drivers)
            + (" (" + "; ".join(errors) + ")" if errors else "")
        )

    def connect(self, cfg: dict):  # pragma: no cover - overridden
        raise NotImplementedError

    def paramstyle(self, module) -> str:
        return getattr(module, "paramstyle", "qmark")

    def init_connection(self, raw) -> None:
        """Hook executed on every new connection."""

    # ------------------------------------------------------------------ types
    def type_sql(self, col: Column) -> str:
        match col.kind:
            case "pk":
                return "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"
            case "int":
                return "BIGINT"
            case "varchar":
                return f"VARCHAR({col.length or 255})"
            case "text":
                return "TEXT"
            case "decimal":
                return f"DECIMAL({col.precision or 18},{col.scale if col.scale is not None else 2})"
            case "float":
                return "DOUBLE PRECISION"
            case "bool":
                return "BOOLEAN"
            case "date":
                return "DATE"
            case "datetime":
                return "TIMESTAMP"
        raise DialectError(f"Unknown column kind {col.kind!r}")

    def column_sql(self, col: Column) -> str:
        sql = f"{self.quote(col.name)} {self.type_sql(col)}"
        if col.kind != "pk" and not col.nullable:
            sql += " NOT NULL"
        return sql

    # ------------------------------------------------------------------ DDL
    def create_table_sql(self, table: Table, if_not_exists: bool = True) -> list[str]:
        cols = ",\n  ".join(self.column_sql(c) for c in table.columns)
        ine = "IF NOT EXISTS " if if_not_exists else ""
        stmts = [f"CREATE TABLE {ine}{self.quote(table.name)} (\n  {cols}\n)"]
        for name, cols_, unique in table.indexes:
            stmts.append(self.create_index_sql(name, table.name, cols_, unique, if_not_exists))
        return stmts

    def create_index_sql(self, name, table, cols, unique=False, if_not_exists=True) -> str:
        u = "UNIQUE " if unique else ""
        ine = "IF NOT EXISTS " if if_not_exists else ""
        collist = ", ".join(self.quote(c) for c in cols)
        return f"CREATE {u}INDEX {ine}{self.quote(name)} ON {self.quote(table)} ({collist})"

    def add_column_sql(self, table: str, col: Column) -> str:
        return f"ALTER TABLE {self.quote(table)} ADD COLUMN {self.column_sql(col)}"

    def drop_column_sql(self, table: str, column: str) -> str:
        return f"ALTER TABLE {self.quote(table)} DROP COLUMN {self.quote(column)}"

    def drop_table_sql(self, table: str) -> str:
        return f"DROP TABLE IF EXISTS {self.quote(table)}"

    def table_exists_sql(self) -> str:
        return "SELECT COUNT(*) FROM information_schema.tables WHERE table_name = ?"

    # ------------------------------------------------------------------ DML
    def limit_sql(self, limit: int | None, offset: int = 0) -> str:
        if limit is None:
            return f" OFFSET {int(offset)}" if offset else ""
        return f" LIMIT {int(limit)} OFFSET {int(offset)}"

    def insert_sql(self, table: str, cols: list[str], return_id: bool) -> str:
        t = self.quote(table)
        if cols:
            collist = ", ".join(self.quote(c) for c in cols)
            marks = ", ".join("?" for _ in cols)
            sql = f"INSERT INTO {t} ({collist}) VALUES ({marks})"
        else:
            sql = f"INSERT INTO {t} DEFAULT VALUES"
        if return_id and self.id_strategy == "returning":
            sql += f" RETURNING {self.quote('id')}"
        return sql

    def explicit_id_begin(self, table: str) -> list[str]:
        return []

    def explicit_id_end(self, table: str) -> list[str]:
        return []

    def fold_sql(self, expr: str) -> str:
        """SQL version of :func:`fold_text`: lower case, Turkish dotless/dotted i as "i"."""
        dotless, dot = self.string_literal("\u0131"), self.string_literal("\u0307")
        return f"REPLACE(REPLACE(LOWER({expr}), {dotless}, 'i'), {dot}, '')"

    def like_sql(self, expr: str) -> str:
        return f"{self.fold_sql(expr)} LIKE ? ESCAPE '!'"

    @staticmethod
    def escape_like(text: str) -> str:
        return text.replace("!", "!!").replace("%", "!%").replace("_", "!_")

    def search_term(self, text: str) -> str:
        """Prepare a search text for :meth:`like_sql` (``%`` and ``_`` match literally)."""
        return "%" + self.escape_like(fold_text(text.strip())) + "%"

    def cast_text_sql(self, expr: str) -> str:
        return f"CAST({expr} AS VARCHAR(255))"

    # ------------------------------------------------------------------ literals
    def string_literal(self, value: str) -> str:
        return "'" + value.replace("'", "''") + "'"

    def bool_literal(self, value: bool) -> str:
        return "TRUE" if value else "FALSE"

    def literal(self, value) -> str:
        """Render a Python value as an SQL literal for dump files."""
        if value is None:
            return "NULL"
        if isinstance(value, bool):
            return self.bool_literal(value)
        if isinstance(value, int):
            return str(value)
        if isinstance(value, float):
            if value != value or value in (float("inf"), float("-inf")):
                return "NULL"
            return repr(value)
        if isinstance(value, decimal.Decimal):
            return format(value, "f")
        if isinstance(value, dt.datetime):
            return self.string_literal(value.replace(tzinfo=None).isoformat(sep=" "))
        if isinstance(value, dt.date):
            return self.string_literal(value.isoformat())
        if isinstance(value, (bytes, bytearray, memoryview)):
            return "X'" + bytes(value).hex() + "'"
        return self.string_literal(str(value))

    def comment(self, text: str) -> str:
        return "\n".join("-- " + line for line in text.splitlines())

    def dump_preamble(self) -> list[str]:
        return []

    def dump_postamble(self) -> list[str]:
        return []

    def statement_terminator(self) -> str:
        return ";"


class SQLiteDialect(Dialect):
    name = "sqlite"
    title = "SQLite"
    drivers = ("sqlite3",)
    needs_server = False

    def connect(self, cfg: dict):
        import sqlite3

        _register_sqlite_types(sqlite3)
        path = cfg.get("name") or cfg.get("path") or "erp.sqlite3"
        conn = sqlite3.connect(
            path, detect_types=sqlite3.PARSE_DECLTYPES, check_same_thread=False, timeout=30
        )
        conn.execute("PRAGMA foreign_keys = ON")
        conn.create_function("erp_fold", 1, fold_text, deterministic=True)
        if path != ":memory:":
            conn.execute("PRAGMA journal_mode = WAL")
        return conn

    def paramstyle(self, module) -> str:
        return "qmark"

    def type_sql(self, col: Column) -> str:
        match col.kind:
            case "pk":
                return "INTEGER PRIMARY KEY AUTOINCREMENT"
            case "int":
                return "INTEGER"
            case "float":
                return "REAL"
            case "datetime":
                return "DATETIME"
        return super().type_sql(col)

    def table_exists_sql(self) -> str:
        return "SELECT COUNT(*) FROM sqlite_master WHERE type = 'table' AND name = ?"

    def bool_literal(self, value: bool) -> str:
        return "1" if value else "0"

    def limit_sql(self, limit, offset=0) -> str:
        if limit is None:
            return f" LIMIT -1 OFFSET {int(offset)}" if offset else ""
        return super().limit_sql(limit, offset)

    def cast_text_sql(self, expr: str) -> str:
        return f"CAST({expr} AS TEXT)"

    def like_sql(self, expr: str) -> str:
        # SQLite's LOWER() only knows ASCII; use a Unicode aware function.
        return f"erp_fold({expr}) LIKE ? ESCAPE '!'"

    def search_term(self, text: str) -> str:
        return "%" + self.escape_like(fold_text(text.strip())) + "%"

    def dump_preamble(self) -> list[str]:
        return ["PRAGMA foreign_keys = OFF", "BEGIN TRANSACTION"]

    def dump_postamble(self) -> list[str]:
        return ["COMMIT"]


class MySQLDialect(Dialect):
    name = "mysql"
    title = "MySQL"
    quote_open = "`"
    quote_close = "`"
    default_port = 3306
    drivers = ("pymysql",)

    def connect(self, cfg: dict):
        mod = self.load_driver(cfg.get("driver") or None)
        return mod.connect(
            host=cfg.get("host") or "localhost",
            port=int(cfg.get("port") or self.default_port),
            user=cfg.get("user") or "",
            password=cfg.get("password") or "",
            database=cfg.get("name") or "",
            charset="utf8mb4",
            autocommit=False,
        )

    def init_connection(self, raw) -> None:
        cur = raw.cursor()
        cur.execute("SET time_zone = '+00:00'")
        cur.close()

    def type_sql(self, col: Column) -> str:
        match col.kind:
            case "pk":
                return "BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY"
            case "text":
                return "LONGTEXT"
            case "float":
                return "DOUBLE"
            case "bool":
                return "TINYINT(1)"
            case "datetime":
                return "DATETIME(6)"
        return super().type_sql(col)

    def create_table_sql(self, table: Table, if_not_exists: bool = True) -> list[str]:
        # MySQL has no "CREATE INDEX IF NOT EXISTS", so indexes are part of CREATE TABLE.
        parts = [self.column_sql(c) for c in table.columns]
        for name, cols, unique in table.indexes:
            collist = ", ".join(self.quote(c) for c in cols)
            parts.append(f"{'UNIQUE ' if unique else ''}KEY {self.quote(name)} ({collist})")
        ine = "IF NOT EXISTS " if if_not_exists else ""
        body = ",\n  ".join(parts)
        return [f"CREATE TABLE {ine}{self.quote(table.name)} (\n  {body}\n) "
                "ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci"]

    def create_index_sql(self, name, table, cols, unique=False, if_not_exists=True) -> str:
        return super().create_index_sql(name, table, cols, unique, False)

    def table_exists_sql(self) -> str:
        return (
            "SELECT COUNT(*) FROM information_schema.tables "
            "WHERE table_schema = DATABASE() AND table_name = ?"
        )

    def insert_sql(self, table, cols, return_id) -> str:
        if not cols:
            return f"INSERT INTO {self.quote(table)} () VALUES ()"
        return super().insert_sql(table, cols, return_id)

    def string_literal(self, value: str) -> str:
        value = value.replace("\\", "\\\\").replace("'", "''").replace("\x00", "\\0")
        return "'" + value + "'"

    def bool_literal(self, value: bool) -> str:
        return "1" if value else "0"

    def cast_text_sql(self, expr: str) -> str:
        return f"CAST({expr} AS CHAR)"

    def dump_preamble(self) -> list[str]:
        return [
            "SET NAMES utf8mb4",
            "SET FOREIGN_KEY_CHECKS = 0",
            "START TRANSACTION",
        ]

    def dump_postamble(self) -> list[str]:
        return ["COMMIT", "SET FOREIGN_KEY_CHECKS = 1"]


class MariaDBDialect(MySQLDialect):
    name = "mariadb"
    title = "MariaDB"
    drivers = ("pymysql", "mariadb")

    def connect(self, cfg: dict):
        driver = cfg.get("driver") or "pymysql"
        if driver == "mariadb":  # pragma: no cover - optional connector
            mod = self.load_driver("mariadb")
            return mod.connect(
                host=cfg.get("host") or "localhost",
                port=int(cfg.get("port") or self.default_port),
                user=cfg.get("user") or "",
                password=cfg.get("password") or "",
                database=cfg.get("name") or "",
                autocommit=False,
            )
        return super().connect(cfg)


class MSSQLDialect(Dialect):
    name = "mssql"
    title = "Microsoft SQL Server"
    quote_open = "["
    quote_close = "]"
    default_port = 1433
    id_strategy = "output"
    drivers = ("pyodbc", "pymssql")

    def connect(self, cfg: dict):
        driver = cfg.get("driver") or None
        mod = self.load_driver(driver)
        host = cfg.get("host") or "localhost"
        port = int(cfg.get("port") or self.default_port)
        if mod.__name__ == "pyodbc":
            odbc = cfg.get("odbc_driver") or "ODBC Driver 18 for SQL Server"
            parts = [
                f"DRIVER={{{odbc}}}",
                f"SERVER={host},{port}",
                f"DATABASE={cfg.get('name') or ''}",
                f"UID={cfg.get('user') or ''}",
                "PWD={" + (cfg.get("password") or "").replace("}", "}}") + "}",
                "TrustServerCertificate=" + ("yes" if cfg.get("trust_server_certificate", True) else "no"),
                "Encrypt=" + ("yes" if cfg.get("encrypt", True) else "no"),
            ]
            return mod.connect(";".join(parts), autocommit=False)
        return mod.connect(  # pragma: no cover - pymssql
            server=host,
            port=str(port),
            user=cfg.get("user") or "",
            password=cfg.get("password") or "",
            database=cfg.get("name") or "",
            autocommit=False,
        )

    def type_sql(self, col: Column) -> str:
        match col.kind:
            case "pk":
                return "BIGINT IDENTITY(1,1) NOT NULL PRIMARY KEY"
            case "varchar":
                n = col.length or 255
                return f"NVARCHAR({n})" if n <= 4000 else "NVARCHAR(MAX)"
            case "text":
                return "NVARCHAR(MAX)"
            case "float":
                return "FLOAT"
            case "bool":
                return "BIT"
            case "datetime":
                return "DATETIME2"
        return super().type_sql(col)

    def create_table_sql(self, table: Table, if_not_exists: bool = True) -> list[str]:
        stmts = super().create_table_sql(table, False)
        if if_not_exists:
            lit = self.string_literal(table.name)
            stmts[0] = f"IF OBJECT_ID({lit}, 'U') IS NULL\n" + stmts[0]
        return stmts

    def create_index_sql(self, name, table, cols, unique=False, if_not_exists=True) -> str:
        sql = super().create_index_sql(name, table, cols, unique, False)
        if if_not_exists:
            sql = (
                f"IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = {self.string_literal(name)})\n"
                + sql
            )
        return sql

    def add_column_sql(self, table: str, col: Column) -> str:
        return f"ALTER TABLE {self.quote(table)} ADD {self.column_sql(col)}"

    def drop_table_sql(self, table: str) -> str:
        return f"IF OBJECT_ID({self.string_literal(table)}, 'U') IS NOT NULL DROP TABLE {self.quote(table)}"

    def table_exists_sql(self) -> str:
        return "SELECT COUNT(*) FROM INFORMATION_SCHEMA.TABLES WHERE TABLE_NAME = ?"

    def limit_sql(self, limit, offset=0) -> str:
        # Requires an ORDER BY clause, which the application always provides.
        sql = f" OFFSET {int(offset)} ROWS"
        if limit is not None:
            sql += f" FETCH NEXT {int(limit)} ROWS ONLY"
        return sql

    def insert_sql(self, table, cols, return_id) -> str:
        t = self.quote(table)
        out = f" OUTPUT INSERTED.{self.quote('id')}" if return_id else ""
        if not cols:
            return f"INSERT INTO {t}{out} DEFAULT VALUES"
        collist = ", ".join(self.quote(c) for c in cols)
        marks = ", ".join("?" for _ in cols)
        return f"INSERT INTO {t} ({collist}){out} VALUES ({marks})"

    def explicit_id_begin(self, table: str) -> list[str]:
        return [f"SET IDENTITY_INSERT {self.quote(table)} ON"]

    def explicit_id_end(self, table: str) -> list[str]:
        return [f"SET IDENTITY_INSERT {self.quote(table)} OFF"]

    def cast_text_sql(self, expr: str) -> str:
        return f"CAST({expr} AS NVARCHAR(4000))"

    @staticmethod
    def escape_like(text: str) -> str:
        return Dialect.escape_like(text).replace("[", "![")

    def string_literal(self, value: str) -> str:
        return "N'" + value.replace("'", "''") + "'"

    def bool_literal(self, value: bool) -> str:
        return "1" if value else "0"

    def literal(self, value) -> str:
        if isinstance(value, dt.datetime):
            return "'" + value.replace(tzinfo=None).isoformat(sep="T") + "'"
        if isinstance(value, (bytes, bytearray, memoryview)):
            return "0x" + bytes(value).hex()
        return super().literal(value)

    def dump_preamble(self) -> list[str]:
        return ["SET XACT_ABORT ON", "BEGIN TRANSACTION"]

    def dump_postamble(self) -> list[str]:
        return ["COMMIT TRANSACTION"]


class PostgreSQLDialect(Dialect):
    name = "postgresql"
    title = "PostgreSQL"
    default_port = 5432
    id_strategy = "returning"
    drivers = ("psycopg", "psycopg2")

    def connect(self, cfg: dict):
        mod = self.load_driver(cfg.get("driver") or None)
        return mod.connect(
            host=cfg.get("host") or "localhost",
            port=int(cfg.get("port") or self.default_port),
            user=cfg.get("user") or "",
            password=cfg.get("password") or "",
            dbname=cfg.get("name") or "",
        )

    def init_connection(self, raw) -> None:
        cur = raw.cursor()
        cur.execute("SET TIME ZONE 'UTC'")
        cur.close()
        raw.commit()

    def table_exists_sql(self) -> str:
        return (
            "SELECT COUNT(*) FROM information_schema.tables "
            "WHERE table_schema = current_schema() AND table_name = ?"
        )

    def explicit_id_end(self, table: str) -> list[str]:
        t = self.quote(table)
        name = self.string_literal(table)
        return [
            f"SELECT setval(pg_get_serial_sequence({name}, 'id'), "
            f"COALESCE((SELECT MAX({self.quote('id')}) FROM {t}), 0) + 1, false)"
        ]

    def cast_text_sql(self, expr: str) -> str:
        return f"CAST({expr} AS TEXT)"

    def literal(self, value) -> str:
        if isinstance(value, (bytes, bytearray, memoryview)):
            return "'\\x" + bytes(value).hex() + "'::bytea"
        return super().literal(value)

    def dump_preamble(self) -> list[str]:
        return ["SET client_encoding = 'UTF8'", "BEGIN"]

    def dump_postamble(self) -> list[str]:
        return ["COMMIT"]


def fold_text(value):
    """Case folding for searches that treats Turkish dotted/dotless i alike."""
    if value is None:
        return None
    text = str(value)
    for ch in ("İ", "I", "ı"):
        text = text.replace(ch, "i")
    return text.lower()


_SQLITE_REGISTERED = False


def _register_sqlite_types(sqlite3) -> None:
    global _SQLITE_REGISTERED
    if _SQLITE_REGISTERED:
        return
    sqlite3.register_adapter(dt.datetime, lambda v: v.replace(tzinfo=None).isoformat(sep=" "))
    sqlite3.register_adapter(dt.date, lambda v: v.isoformat())
    sqlite3.register_adapter(decimal.Decimal, lambda v: format(v, "f"))

    def conv_datetime(b: bytes):
        try:
            return dt.datetime.fromisoformat(b.decode())
        except ValueError:
            return b.decode()

    def conv_date(b: bytes):
        try:
            return dt.date.fromisoformat(b.decode()[:10])
        except ValueError:
            return b.decode()

    def conv_decimal(b: bytes):
        try:
            return decimal.Decimal(b.decode())
        except decimal.InvalidOperation:
            return b.decode()

    sqlite3.register_converter("DATETIME", conv_datetime)
    sqlite3.register_converter("TIMESTAMP", conv_datetime)
    sqlite3.register_converter("DATE", conv_date)
    sqlite3.register_converter("DECIMAL", conv_decimal)
    sqlite3.register_converter("BOOLEAN", lambda b: b not in (b"0", b"", b"false"))
    _SQLITE_REGISTERED = True


DIALECTS: dict[str, Dialect] = {
    d.name: d
    for d in (SQLiteDialect(), MySQLDialect(), MariaDBDialect(), MSSQLDialect(), PostgreSQLDialect())
}


def get_dialect(name: str) -> Dialect:
    try:
        return DIALECTS[name]
    except KeyError:
        raise DialectError(f"Unsupported database system: {name!r}") from None
